package facts

import (
	"bytes"
	"context"
	"path"
	"slices"
	"strings"
)

// headerLines is how many lines from the top of a blob are read for a
// generated marker. Blank lines count toward it.
const headerLines = 20

// commentLeaders start a header line: Go, TS, JS, C#, Python, shell, YAML,
// TOML, HTML, XML, SQL and ini comments.
var commentLeaders = []string{"//", "/*", "*", "#", "<!--", "--", ";"}

// generatedMarkers are matched, case-insensitively, inside a header line. The
// word "generated" alone is not one: it is too common in ordinary comments.
var generatedMarkers = []string{"do not edit", "do not modify", "@generated", "<auto-generated"}

// GeneratedHeader reports whether content carries a generated marker in its
// header: the comment lines among its first headerLines lines, ending at the
// first line that is neither blank nor a comment. A leading UTF-8 BOM is
// dropped and a trailing "\r" is stripped from each line. Content git treats
// as binary has no header.
func GeneratedHeader(content []byte) bool {
	if !isText(content) {
		return false
	}
	content = bytes.TrimPrefix(content, []byte("\xef\xbb\xbf"))
	lines := strings.SplitN(string(content), "\n", headerLines+1)
	if len(lines) > headerLines {
		lines = lines[:headerLines]
	}
	for _, line := range lines {
		line = strings.Trim(strings.TrimSuffix(line, "\r"), " \t")
		if line == "" {
			continue
		}
		if !hasCommentLeader(line) {
			return false
		}
		lower := strings.ToLower(line)
		for _, m := range generatedMarkers {
			if strings.Contains(lower, m) {
				return true
			}
		}
	}
	return false
}

// shellInterpreters are the interpreters whose shebang makes an extensionless
// file a Shell script.
var shellInterpreters = []string{"sh", "bash", "dash", "zsh", "ksh"}

// ShellShebang reports whether content's first line is a shell shebang: "#!"
// then one of shellInterpreters, by path (#!/bin/bash) or through env
// (#!/usr/bin/env bash, env options and VAR=x assignments skipped). A leading
// UTF-8 BOM is dropped and a trailing "\r" stripped. Content git treats as
// binary has no shebang.
func ShellShebang(content []byte) bool {
	if !isText(content) {
		return false
	}
	content = bytes.TrimPrefix(content, []byte("\xef\xbb\xbf"))
	line, _, _ := strings.Cut(string(content), "\n")
	line = strings.TrimSuffix(line, "\r")
	rest, ok := strings.CutPrefix(line, "#!")
	if !ok {
		return false
	}
	fields := strings.Fields(rest)
	if len(fields) > 0 && path.Base(fields[0]) == "env" {
		fields = fields[1:]
		for len(fields) > 0 && (strings.HasPrefix(fields[0], "-") || strings.Contains(fields[0], "=")) {
			fields = fields[1:]
		}
	}
	return len(fields) > 0 && slices.Contains(shellInterpreters, path.Base(fields[0]))
}

func hasCommentLeader(line string) bool {
	for _, l := range commentLeaders {
		if strings.HasPrefix(line, l) {
			return true
		}
	}
	return false
}

// withClass returns classes with c added, rebuilt in Class order (the order of
// builtin), each at most once.
func withClass(classes []Class, c Class) []Class {
	has := map[Class]bool{c: true}
	for _, x := range classes {
		has[x] = true
	}
	out := make([]Class, 0, len(has))
	for _, b := range builtin {
		if has[b.class] {
			out = append(out, b.class)
		}
	}
	return out
}

// markHeads reads each changed file, not already generated, at commit. A
// file whose header carries a generated marker is classed generated; an
// extensionless file whose first line is a shell shebang names Shell as its
// Language. A path with no regular-file blob at commit (deleted, or planned
// new) keeps its path classes and names no language.
func markHeads(ctx context.Context, repo, commit string, files []File) error {
	idx := map[string]int{}
	for i, f := range files {
		if !slices.Contains(f.Classes, ClassGenerated) {
			idx[f.Path] = i
		}
	}
	if len(idx) == 0 {
		return nil
	}
	tree, err := treeBlobs(ctx, repo, commit)
	if err != nil {
		return err
	}
	var read []blob
	for _, b := range tree {
		if _, ok := idx[b.path]; ok {
			read = append(read, b)
		}
	}
	return catBlobs(ctx, repo, read, func(p string, content []byte) {
		i := idx[p]
		if GeneratedHeader(content) {
			files[i].Classes = withClass(files[i].Classes, ClassGenerated)
		}
		if path.Ext(path.Base(p)) == "" && ShellShebang(content) {
			files[i].Language = scriptLanguage
		}
	})
}
